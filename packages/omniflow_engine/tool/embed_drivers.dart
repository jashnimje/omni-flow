import 'dart:io';

/// Regenerates `lib/src/manifest/built_in_drivers.g.dart` from the repo's
/// `drivers/*.omni_driver.json`, so built-in manifests load the same way in
/// the CLI, in tests and in an AOT-compiled app.
///
/// Run from `packages/omniflow_engine`: `dart run tool/embed_drivers.dart`.
const driversDir = '../../drivers';
const outputPath = 'lib/src/manifest/built_in_drivers.g.dart';
const _suffix = '.omni_driver.json';

String generateBuiltInDrivers(Directory dir) {
  final files =
      dir
          .listSync()
          .whereType<File>()
          .where((f) => f.path.endsWith(_suffix))
          .toList()
        ..sort((a, b) => a.path.compareTo(b.path));
  final out = StringBuffer()
    ..writeln(
      '// GENERATED by tool/embed_drivers.dart from drivers/. Do not edit.',
    )
    ..writeln()
    ..writeln('/// Built-in driver manifest sources, keyed by file name.')
    ..writeln('const builtInDriverSources = <String, String>{');
  for (final file in files) {
    final name = file.uri.pathSegments.last;
    final source = file.readAsStringSync();
    if (source.contains("'''")) {
      throw StateError('$name contains a triple quote and cannot be embedded');
    }
    out
      ..writeln("  '$name': r'''")
      ..write(source)
      ..writeln("''',");
  }
  out.writeln('};');
  return out.toString();
}

void main(List<String> args) {
  final generated = generateBuiltInDrivers(Directory(driversDir));
  if (args.contains('--check')) {
    final current = File(outputPath).existsSync()
        ? File(outputPath).readAsStringSync()
        : '';
    if (current != generated) {
      stderr.writeln(
        '$outputPath is stale. Run: dart run tool/embed_drivers.dart',
      );
      exitCode = 1;
    }
    return;
  }
  File(outputPath).writeAsStringSync(generated);
  stdout.writeln('wrote $outputPath');
}
